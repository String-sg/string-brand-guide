#!/usr/bin/env node
// Run from a reviewed branding checkout; never downloads code during a product build.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const products = {
  landing: { repo: 'String-sg/string-sg-landing', name: 'string-site', framework: 'astro' },
  id: { repo: 'ghostleek/string-id', name: 'string-id', framework: 'react' },
  skills: { repo: 'String-sg/str-skills', name: 'string-skills', framework: 'react' },
  bingo: { repo: 'String-sg/bingo-string', name: 'string-bingo', framework: 'html' },
};
const [product, target, flag] = process.argv.slice(2);
if (!products[product] || !target || (flag && flag !== '--check')) {
  throw new Error('Usage: node sync.mjs <landing|id|skills|bingo> <checkout> [--check]');
}
const config = products[product];
const root = resolve(target);
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
if (pkg.name !== config.name) throw new Error(`Expected ${config.name}, got ${pkg.name}`);
const source = dirname(fileURLToPath(import.meta.url));
const template = await readFile(join(source, 'footer.html'), 'utf8');
const css = await readFile(join(source, 'footer.css'), 'utf8');
const logo = await readFile(join(source, 'string-logo.svg'), 'utf8');
const html = template.replace('{{source}}', `https://github.com/${config.repo}`);
const hash = createHash('sha256').update(template).update(css).update(logo).digest('hex');
const files = new Map([
  ['public/string-footer/string-logo.svg', logo],
  ['string-footer.json', JSON.stringify({ version: '1.0.0', source: 'https://github.com/String-sg/string-brand-guide/tree/main/components/string-footer', sha256: hash, product }, null, 2) + '\n'],
]);
if (config.framework === 'html') {
  files.set('styles/string-footer.css', css);
  for (const page of ['index.html', 'new.html']) {
    let content = await readFile(join(root, page), 'utf8');
    const start = '<!-- string-footer:start -->';
    const end = '<!-- string-footer:end -->';
    const block = `${start}\n${html}${end}`;
    if (content.includes(start)) {
      const from = content.indexOf(start), to = content.indexOf(end, from);
      if (to < 0) throw new Error(`Missing footer end marker in ${page}`);
      content = content.slice(0, from) + block + content.slice(to + end.length);
    } else {
      content = content.replace('</body>', `${block}\n</body>`);
    }
    if (!content.includes('href="/styles/string-footer.css"')) {
      content = content.replace('</head>', '    <link rel="stylesheet" href="/styles/string-footer.css">\n</head>');
    }
    files.set(page, content);
  }
} else {
  files.set('src/components/string-footer/footer.css', css);
  if (config.framework === 'react') {
    files.set('src/components/string-footer/StringFooter.tsx',
      `// Generated by String-sg/string-brand-guide/components/string-footer/sync.mjs.\nimport './footer.css';\n\nexport default function StringFooter() {\n  return (\n${html.replaceAll('class=', 'className=').split('\n').filter(Boolean).map(line => '    ' + line).join('\n')}\n  );\n}\n`);
  } else {
    files.set('src/components/string-footer/StringFooter.astro',
      `---\n// Generated by String-sg/string-brand-guide/components/string-footer/sync.mjs.\nimport './footer.css';\n---\n${html}`);
  }
}
for (const [path, content] of files) {
  const destination = join(root, path);
  if (flag === '--check') {
    if (await readFile(destination, 'utf8').catch(() => null) !== content) throw new Error(`Footer drift: ${path}`);
  } else {
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, content);
  }
}
console.log(`${product}: footer ${flag === '--check' ? 'matches' : 'synced'} v1.0.0 (${hash.slice(0, 12)})`);
